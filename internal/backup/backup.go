// Package backup creates and restores portable Zen profile archives.
package backup

import (
	"archive/tar"
	"compress/gzip"
	"encoding/json"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
	"time"

	"github.com/samber/lo"
)

const (
	ManifestName  = "manifest.json"
	ProfilePrefix = "profile/"
	FormatVersion = 1
)

// Manifest describes where a backup came from so it can be relocated.
type Manifest struct {
	FormatVersion int       `json:"format_version"`
	CreatedAt     time.Time `json:"created_at"`
	OS            string    `json:"os"`
	Arch          string    `json:"arch"`
	HomeDir       string    `json:"home_dir"`
	ProfileName   string    `json:"profile_name"`
	ProfilePath   string    `json:"profile_path"`
	ZenVersion    string    `json:"zen_version,omitempty"`
	Slim          bool      `json:"slim"`
	Files         int       `json:"files"`
	Bytes         int64     `json:"bytes"`
}

// Options control what goes into a backup.
type Options struct {
	// Slim skips website storage and rolling session snapshots.
	Slim bool
}

// Paths that are caches, locks, telemetry or machine-specific binaries.
// They are regenerated by Zen and would only bloat or break a restore.
var alwaysExcluded = []string{
	"lock", ".parentlock", "parent.lock",
	"compatibility.ini",     // forces Zen to rebuild caches for the new location
	"addonStartup.json.lz4", // absolute paths; rebuilt from extensions.json
	"cache2", "startupCache", "thumbnails", "OfflineCache", "shader-cache",
	"safebrowsing", "crashes", "minidumps", "datareporting",
	"saved-telemetry-pings", "Crash Reports", "Pending Pings",
	"storage/temporary",
	"gmp-*", // downloaded, platform-specific media plugins
	"*-shm", // sqlite shared-memory index, rebuilt on open
}

var slimExcluded = []string{
	"zen-sessions-backup",
	"sessionstore-backups/upgrade.jsonlz4-*",
	"sessionstore-backups/previous.jsonlz4",
}

// Website data lives in storage/default/<scheme>+++<host>; extension data
// (moz-extension+++…) is kept even in slim mode.
var websiteStorage = regexp.MustCompile(`^storage/default/https?\+\+\+[^/]*(/|$)`)

// Excluded reports whether a profile-relative, slash-separated path is skipped.
func Excluded(rel string, opts Options) bool {
	matches := func(pattern string) bool { return matchesPattern(pattern, rel) }
	if lo.SomeBy(alwaysExcluded, matches) {
		return true
	}
	return opts.Slim && (websiteStorage.MatchString(rel) || lo.SomeBy(slimExcluded, matches))
}

func matchesPattern(pattern, rel string) bool {
	switch {
	case strings.Contains(pattern, "/"):
		ok, _ := path.Match(pattern, rel)
		return ok || rel == pattern || strings.HasPrefix(rel, pattern+"/")
	case strings.HasPrefix(pattern, "*"):
		// Suffix patterns like *-shm match files at any depth.
		ok, _ := path.Match(pattern, path.Base(rel))
		return ok
	default:
		// Other patterns match a top-level entry and everything under it.
		top, _, _ := strings.Cut(rel, "/")
		ok, _ := path.Match(pattern, top)
		return ok
	}
}

// profileEntry is a file or directory to include in a backup.
type profileEntry struct {
	rel  string // slash-separated path relative to the profile dir
	info fs.FileInfo
}

// Create writes a backup of profileDir to archivePath.
func Create(profileDir, profileName, zenVersion, archivePath string, opts Options, progress Progress) (Manifest, error) {
	entries, err := scanProfile(profileDir, opts)
	if err != nil {
		return Manifest{}, fmt.Errorf("scanning profile: %w", err)
	}
	files := lo.Filter(entries, func(e profileEntry, _ int) bool { return !e.info.IsDir() })

	home, _ := os.UserHomeDir()
	m := Manifest{
		FormatVersion: FormatVersion,
		CreatedAt:     time.Now().UTC().Truncate(time.Second),
		OS:            runtime.GOOS,
		Arch:          runtime.GOARCH,
		HomeDir:       home,
		ProfileName:   profileName,
		ProfilePath:   profileDir,
		ZenVersion:    zenVersion,
		Slim:          opts.Slim,
		Files:         len(files),
		Bytes:         lo.SumBy(files, func(e profileEntry) int64 { return e.info.Size() }),
	}

	err = writeFileAtomically(archivePath, func(w io.Writer) error {
		return writeArchive(w, profileDir, m, entries, progress)
	})
	return m, err
}

// scanProfile lists the regular files and directories to back up.
func scanProfile(profileDir string, opts Options) ([]profileEntry, error) {
	var entries []profileEntry
	err := filepath.WalkDir(profileDir, func(p string, d fs.DirEntry, err error) error {
		if err != nil || p == profileDir {
			return err
		}
		rel, err := filepath.Rel(profileDir, p)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		excluded := Excluded(rel, opts)
		switch {
		case excluded && d.IsDir():
			return filepath.SkipDir
		case excluded:
			return nil
		case !d.IsDir() && !d.Type().IsRegular():
			return nil // symlinks, sockets, etc.
		}
		info, err := d.Info()
		if err != nil {
			return err
		}
		entries = append(entries, profileEntry{rel, info})
		return nil
	})
	return entries, err
}

// writeFileAtomically writes to a temporary file next to path and renames it
// into place only if write succeeds, so a failure never leaves a partial file.
func writeFileAtomically(path string, write func(io.Writer) error) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".zen-backup-*.partial")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(tmp.Name()) }()

	if err := write(tmp); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// writeArchive writes a gzipped tar with the manifest followed by the profile.
func writeArchive(w io.Writer, profileDir string, m Manifest, entries []profileEntry, progress Progress) error {
	gz := gzip.NewWriter(w)
	tw := tar.NewWriter(gz)

	if err := writeManifest(tw, m); err != nil {
		return err
	}
	tracker := progressTracker{report: progress}
	for _, e := range entries {
		if err := writeEntry(tw, profileDir, e); err != nil {
			return fmt.Errorf("%s: %w", e.rel, err)
		}
		if !e.info.IsDir() {
			tracker.add(e.info.Size())
		}
	}
	tracker.flush()

	if err := tw.Close(); err != nil {
		return err
	}
	return gz.Close()
}

func writeManifest(tw *tar.Writer, m Manifest) error {
	data, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	hdr := &tar.Header{Name: ManifestName, Mode: 0o644, Size: int64(len(data)), ModTime: m.CreatedAt, Typeflag: tar.TypeReg}
	if err := tw.WriteHeader(hdr); err != nil {
		return err
	}
	_, err = tw.Write(data)
	return err
}

func writeEntry(tw *tar.Writer, profileDir string, e profileEntry) error {
	hdr, err := tar.FileInfoHeader(e.info, "")
	if err != nil {
		return err
	}
	hdr.Name = ProfilePrefix + e.rel
	hdr.Uname, hdr.Gname, hdr.Uid, hdr.Gid = "", "", 0, 0
	if e.info.IsDir() {
		hdr.Name += "/"
		return tw.WriteHeader(hdr)
	}
	if err := tw.WriteHeader(hdr); err != nil {
		return err
	}
	return copyFile(tw, filepath.Join(profileDir, filepath.FromSlash(e.rel)), hdr.Size)
}

// copyFile writes exactly size bytes of src, tolerating files that changed
// size since they were scanned (truncating or zero-padding).
func copyFile(w io.Writer, src string, size int64) error {
	f, err := os.Open(src)
	if err != nil {
		return err
	}
	defer func() { _ = f.Close() }()
	n, err := io.Copy(w, io.LimitReader(f, size))
	if err != nil {
		return err
	}
	if n < size {
		_, err = io.CopyN(w, zeroReader{}, size-n)
	}
	return err
}

type zeroReader struct{}

func (zeroReader) Read(p []byte) (int, error) {
	clear(p)
	return len(p), nil
}

var unsafeChars = regexp.MustCompile(`[^A-Za-z0-9._-]+`)

// ArchiveName builds a file name like zen-backup_Default_2024-01-02_15-04-05.tar.gz.
func ArchiveName(profileName string, t time.Time) string {
	n := strings.Trim(unsafeChars.ReplaceAllString(profileName, "-"), "-")
	if n == "" {
		n = "profile"
	}
	return fmt.Sprintf("zen-backup_%s_%s.tar.gz", n, t.Format("2006-01-02_15-04-05"))
}
